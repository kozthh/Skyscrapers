package topics.Foundations.input_output_and_debugging.Basics.HandsOnExcercises.Declaration;

public class Datatypes {

    public static void main(String[] args) {
        String name = "Kenneth";
        int age = 18;
        double monthlyIncome = 5000000.50;
        boolean isPogi = true;
        char gender = 'M';
        long bankBalance = 1000000000000L;

        System.out.println("Name is: " + name);
        System.out.println("Age is: " + age);
        System.out.println("Monthly income is: " + monthlyIncome);
        System.out.println("Gender is: " + gender);
        System.out.println("isPogi is: " + isPogi);
        System.out.println("Bank balance is: " + bankBalance);
    }
}
